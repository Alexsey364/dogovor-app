def _fmt_date(d):
    if not d:
        d = datetime.date.today()
    if isinstance(d, str):
        try:
            d = datetime.date.fromisoformat(d)
        except ValueError:
            return d
    return f"«{d.day:02d}» {MONTHS_RU[d.month]} {d.year} г."


def _yr(d):
    if isinstance(d, str):
        try:
            return datetime.date.fromisoformat(d).year
        except ValueError:
            return datetime.date.today().year
    return d.year if d else datetime.date.today().year


def _money(v):
    try:
        return f"{float(v):,.2f}".replace(",", " ").replace(".", ",") + " руб."
    except (TypeError, ValueError):
        return "____________ руб."


def _short_fio(full):
    if not full:
        return "____________"
    parts = full.split()
    if len(parts) >= 3:
        return f"{parts[1][0]}.{parts[2][0]}. {parts[0]}"
    return full


class _C:
    """Нумератор разделов и пунктов."""
    def __init__(self, doc):
        self.doc = doc
        self.sec = 0
        self.item = 0

    def h(self, text):
        self.sec += 1
        self.item = 0
        p = self.doc.add_paragraph()
        r = p.add_run(f"{self.sec}. {text}")
        r.bold = True
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)

    def p(self, text):
        self.item += 1
        para = self.doc.add_paragraph(f"{self.sec}.{self.item}. {text}")
        para.paragraph_format.space_after = Pt(2)
        para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        return para

    def sub(self, text):
        """Подпункт-абзац без своей нумерации (перечисление)."""
        para = self.doc.add_paragraph("— " + text)
        para.paragraph_format.space_after = Pt(0)
        para.paragraph_format.left_indent = Pt(18)
        para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def _req_block(doc, party_label, org):
    doc.add_paragraph().add_run(party_label).bold = True
    lines = [org.get("name") or "____________"]
    if org.get("address"):
        lines.append(f"Юридический адрес: {org['address']}")
    ik = "ИНН " + (org.get("inn") or "__________")
    if org.get("kpp"):
        ik += f", КПП {org['kpp']}"
    lines.append(ik)
    if org.get("ogrn"):
        lines.append(f"ОГРН(ИП) {org['ogrn']}")
    if org.get("bank_account"):
        lines.append(f"р/с {org['bank_account']}"
                     + (f" в {org['bank_name']}" if org.get("bank_name") else ""))
    if org.get("corr_account") or org.get("bank_bik"):
        lines.append(f"к/с {org.get('corr_account') or '—'} БИК {org.get('bank_bik') or '—'}")
    if org.get("phone"):
        lines.append(f"тел.: {org['phone']}")
    if org.get("email"):
        lines.append(f"e-mail: {org['email']}")
    for ln in lines:
        p = doc.add_paragraph(ln)
        p.paragraph_format.space_after = Pt(0)


def build(kind, number, sign_date, owner, cp, terms):
    """Собирает развёрнутый .docx договора. Возвращает BytesIO."""
    k = KINDS.get(kind, KINDS["poverka"])
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)

    noun, noun_gen, act = k["noun"], k["noun_gen"], k["act"]
    owner_sign = owner.get("signatory") or "Индивидуальный предприниматель"
    is_ip = "предприниматель" in owner_sign.lower()
    cp_sign = cp.get("signatory") or "руководителя"
    cp_name = cp.get("name") or "____________"
    amount = terms.get("amount")
    advance = terms.get("advance_pct")
    warranty = terms.get("warranty_months") or 30
    deadline = terms.get("deadline_days") or 30
    subject = (terms.get("subject") or "").strip()

    # Заголовок
    ph = doc.add_paragraph()
    ph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = ph.add_run(f"ДОГОВОР № {number}\nна {k['title']}")
    r.bold = True
    r.font.size = Pt(13)

    row = doc.add_paragraph()
    row.add_run("г. Уссурийск")
    row.add_run("\t\t\t\t\t\t" + _fmt_date(sign_date))

    pre = doc.add_paragraph()
    pre.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pre.add_run(
        f"{owner.get('name') or owner_sign}, именуемый(ое) в дальнейшем "
        f"«Исполнитель», в лице {owner_sign} {owner.get('director') or ''}, "
        f"действующего на основании "
        f"{'листа записи ЕГРИП' if is_ip else 'Устава'}, с одной стороны, и "
        f"{cp_name}, именуемое(ый) в дальнейшем «Заказчик», в лице {cp_sign} "
        f"{cp.get('director') or ''}, действующего на основании "
        f"{'Устава' if cp.get('kpp') else 'документа о полномочиях'}, с другой "
        f"стороны, а вместе именуемые «Стороны», заключили настоящий Договор о "
        f"нижеследующем:")

    c = _C(doc)

    # 1. Предмет
    c.h("Предмет Договора")
    c.p(f"Исполнитель обязуется {k['predmet']}"
        + (f" ({subject})" if subject else "")
        + f", а Заказчик обязуется принять и оплатить {noun} в порядке и на "
          f"условиях настоящего Договора.")
    c.p(f"Объём, характеристики, место и сроки определяются настоящим "
        f"Договором и приложениями (спецификацией, заданием, регламентом), "
        f"являющимися его неотъемлемой частью.")
    c.p("Стороны подтверждают, что до заключения Договора согласовали все его "
        "существенные условия.")

    # 2. Права и обязанности сторон
    c.h("Права и обязанности Сторон")
    c.p("Исполнитель обязуется:")
    for it in k["exec"]:
        c.sub(it)
    c.p("Заказчик обязуется:")
    for it in k["cust"]:
        c.sub(it)
    c.sub("своевременно и полностью оплачивать " + noun + " по Договору.")
    c.p("Исполнитель вправе приостановить исполнение и (или) не приступать к "
        f"{noun_gen} до внесения Заказчиком предоплаты, предоставления доступа, "
        "исходных данных и обеспечения готовности объекта. Срок исполнения при "
        "этом продлевается соразмерно задержке, а Исполнитель не несёт "
        "ответственности за такую задержку.")
    c.p("Заказчик несёт ответственность за достоверность переданных сведений и "
        "документов, за готовность объекта и обеспечение доступа. Простой по "
        "вине Заказчика (в т.ч. отсутствие доступа, данных, оплаты) оплачивается "
        "Заказчиком и не влечёт ответственности Исполнителя.")

    # 3. Цена и порядок расчётов
    c.h("Цена Договора и порядок расчётов")
    c.p(f"Общая стоимость {noun_gen} составляет {_money(amount)}. "
        + ("НДС не облагается на основании ст. 145 НК РФ (освобождение от "
           "обязанностей налогоплательщика НДС)." if is_ip else
           "НДС не облагается на основании ст. 145 НК РФ либо НДС 5% — в "
           "зависимости от применяемого Исполнителем режима налогообложения."))
    if advance and float(advance) >= 100:
        c.p("Оплата производится в размере 100% предоплаты в течение 5 (пяти) "
            f"рабочих дней с даты выставления счёта и до начала {noun_gen}. "
            f"Исполнитель приступает к {noun_gen} после поступления оплаты на "
            "расчётный счёт Исполнителя.")
    else:
        pct = int(float(advance)) if advance else 50
        c.p(f"Заказчик выплачивает аванс {pct}% в течение 5 (пяти) рабочих дней "
            f"с даты счёта. Окончательный расчёт — в течение 5 (пяти) рабочих "
            f"дней с даты подписания {act}.")
    c.p("Обязанность по оплате считается исполненной с момента поступления "
        "средств на расчётный счёт Исполнителя. Банковские расходы по "
        "перечислению несёт Заказчик.")
    c.p("Цена является твёрдой. При изменении объёма или состава по инициативе "
        "Заказчика цена и сроки пересматриваются дополнительным соглашением. "
        "Исполнитель вправе в одностороннем порядке зачесть встречные "
        "однородные требования.")

    # 4. Порядок сдачи-приёмки
    c.h("Порядок сдачи и приёмки")
    c.p(f"По завершении Исполнитель передаёт Заказчику {act}. Заказчик обязан в "
        "течение 5 (пяти) рабочих дней подписать акт либо направить "
        "мотивированный письменный отказ с перечнем конкретных недостатков.")
    c.p("Если в указанный срок Заказчик не подписал акт и не направил "
        f"мотивированный отказ, {noun} считаются принятыми в полном объёме и "
        "надлежащего качества, а акт — подписанным Заказчиком в одностороннем "
        "порядке; такой акт является основанием для оплаты.")
    c.p("Немотивированный отказ от подписания акта не освобождает Заказчика от "
        "оплаты. Недостатки, не препятствующие использованию результата, не "
        "являются основанием для отказа от приёмки и оплаты.")

    # 5. Сроки

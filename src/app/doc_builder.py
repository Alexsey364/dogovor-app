    c.p("Персональные данные обрабатываются в целях исполнения Договора в "
        "соответствии с Федеральным законом № 152-ФЗ.")

    # 12. Срок действия
    c.h("Срок действия Договора")
    c.p(f"Договор вступает в силу с даты подписания и действует до 31.12."
        f"{_yr(sign_date)} г., а в части взаиморасчётов и гарантии — до полного "
        "исполнения обязательств. Составлен в двух экземплярах равной силы, по "
        "одному для каждой Стороны.")


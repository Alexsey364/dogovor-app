-- ============================================================
--  Каталог правил проверки
--  Каждое правило можно включить/выключить, у каждого есть
--  краткое и подробное описание. Проверка прогоняет только
--  включённые. Правила с needs_text работают, когда к договору
--  привязан файл и распознан текст.
-- ============================================================

CREATE TABLE IF NOT EXISTS review_rules (
    code        text PRIMARY KEY,
    name        text NOT NULL,          -- краткое описание
    description text,                   -- подробнее: что и почему проверяет
    severity    text NOT NULL DEFAULT 'warning'
        CHECK (severity IN ('critical','warning','info')),
    category    text NOT NULL DEFAULT 'other',
    needs_text  boolean NOT NULL DEFAULT false,
    enabled     boolean NOT NULL DEFAULT true,
    ord         int NOT NULL DEFAULT 100
);

